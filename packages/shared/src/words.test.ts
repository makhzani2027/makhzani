import { describe, expect, it } from 'vitest';
import { amountInWords } from './words';

const w = (n: number, c: 'IQD' | 'USD' = 'IQD') => amountInWords(n, c);

describe('amountInWords — الدينار', () => {
  it('مبالغ الفاتورة المرجعية', () => {
    expect(w(3_770_000)).toBe('فقط ثلاثة ملايين وسبعمائة وسبعون ألف دينار عراقي لا غير');
    expect(w(1_200_000)).toBe('فقط مليون ومائتا ألف دينار عراقي لا غير');
    expect(w(1_020_000)).toBe('فقط مليون وعشرون ألف دينار عراقي لا غير');
    expect(w(125_000)).toBe('فقط مائة وخمسة وعشرون ألف دينار عراقي لا غير');
    expect(w(140_000)).toBe('فقط مائة وأربعون ألف دينار عراقي لا غير');
    expect(w(400_000)).toBe('فقط أربعمائة ألف دينار عراقي لا غير');
  });
  it('الآلاف: مفرد ومثنى وجمع', () => {
    expect(w(1000)).toBe('فقط ألف دينار عراقي لا غير');
    expect(w(2000)).toBe('فقط ألفا دينار عراقي لا غير');
    expect(w(5000)).toBe('فقط خمسة آلاف دينار عراقي لا غير');
    expect(w(10_000)).toBe('فقط عشرة آلاف دينار عراقي لا غير');
    expect(w(11_000)).toBe('فقط أحد عشر ألف دينار عراقي لا غير');
    expect(w(200_000)).toBe('فقط مائتا ألف دينار عراقي لا غير');
    expect(w(250_000)).toBe('فقط مائتان وخمسون ألف دينار عراقي لا غير');
    expect(w(103_000)).toBe('فقط مائة وثلاثة آلاف دينار عراقي لا غير');
  });
  it('مجموعة غير أخيرة: منصوب ومثنى كامل', () => {
    expect(w(70_500)).toBe('فقط سبعون ألفاً وخمسمائة دينار عراقي لا غير');
    expect(w(2_500_000)).toBe('فقط مليونان وخمسمائة ألف دينار عراقي لا غير');
    expect(w(2_000_000)).toBe('فقط مليونا دينار عراقي لا غير');
    expect(w(1500)).toBe('فقط ألف وخمسمائة دينار عراقي لا غير');
    expect(w(12_345_678)).toBe('فقط اثنا عشر مليوناً وثلاثمائة وخمسة وأربعون ألفاً وستمائة وثمانية وسبعون ديناراً عراقياً لا غير');
    expect(w(1_000_000_000)).toBe('فقط مليار دينار عراقي لا غير');
  });
  it('المعدود حسب الآحاد', () => {
    expect(w(1)).toBe('فقط دينار عراقي واحد لا غير');
    expect(w(2)).toBe('فقط ديناران عراقيان لا غير');
    expect(w(7)).toBe('فقط سبعة دنانير عراقية لا غير');
    expect(w(15)).toBe('فقط خمسة عشر ديناراً عراقياً لا غير');
    expect(w(200)).toBe('فقط مائتا دينار عراقي لا غير');
    expect(w(250)).toBe('فقط مائتان وخمسون ديناراً عراقياً لا غير');
    expect(w(1001)).toBe('فقط ألف ودينار عراقي واحد لا غير');
    expect(w(1002)).toBe('فقط ألف وديناران عراقيان لا غير');
    expect(w(21)).toBe('فقط واحد وعشرون ديناراً عراقياً لا غير');
    expect(w(12)).toBe('فقط اثنا عشر ديناراً عراقياً لا غير');
  });
  it('الصفر والتقريب والقيم غير الصالحة', () => {
    expect(w(0)).toBe('صفر دينار عراقي');
    expect(w(999.6)).toBe('فقط ألف دينار عراقي لا غير');
    expect(w(-5)).toBe('');
    expect(w(Number.NaN)).toBe('');
  });
});

describe('amountInWords — الدولار', () => {
  it('دولارات وسنتات', () => {
    expect(w(1250.5, 'USD')).toBe('فقط ألف ومائتان وخمسون دولاراً أمريكياً وخمسون سنتاً لا غير');
    expect(w(3, 'USD')).toBe('فقط ثلاثة دولارات أمريكية لا غير');
    expect(w(100, 'USD')).toBe('فقط مائة دولار أمريكي لا غير');
    expect(w(0.05, 'USD')).toBe('فقط خمسة سنتات لا غير');
    expect(w(1.01, 'USD')).toBe('فقط دولار أمريكي واحد وسنت واحد لا غير');
  });
});
